-- | Manually invoke an animation by ID.
-- If the animation is already running, it will not be started again unless force is True.
invokeAnimation :: SurfaceDefinition -> [ ActiveAnim ] -> Int -> Bool -> IO [ ActiveAnim ]
invokeAnimation surfDef activeAnims animationId force = do
  let runningIds = map (animId . aaDef) activeAnims
      mAnim      = filter (\a -> animId a == animationId) (sdAnimations surfDef)
  case mAnim of
    []         -> return activeAnims
    (anim : _) -> if animationId `elem` runningIds && not force
      then return activeAnims
      else do
        -- Remove existing if force
        let filtered
              = if force
                then filter (\a -> animId (aaDef a) /= animationId) activeAnims
                else activeAnims
        mNewAnim <- startAnimation anim False
        case mNewAnim of
          Nothing      -> return filtered
          Just newAnim -> return (filtered ++ [ newAnim ])

-- | Stop an animation by ID.
stopAnimation :: [ ActiveAnim ] -> Int -> [ ActiveAnim ]
stopAnimation activeAnims animationId = filter (\a -> animId (aaDef a) /= animationId) activeAnims

-- | Stop all currently running animations.
stopAllAnimations :: [ ActiveAnim ] -> [ ActiveAnim ]
stopAllAnimations _ = []

-- | Clear all animations and periodic timers.
clearAnimations :: AnimationState -> IO ()
clearAnimations animState = do
  writeIORef (asActiveAnims animState) []
  writeIORef (asPeriodicState animState) Map.empty
  writeIORef (asExclusiveAnim animState) Nothing
  writeIORef (asAnimQueue animState) []

-- | Toggle a bind animation on/off.
-- When enabled, bind animations are rendered as part of the composite.
toggleBind :: AnimationState -> Int -> IO ()
toggleBind animState animId = do
  modifyIORef' (asBindState animState) $ \binds -> if Set.member animId binds
    then Set.delete animId binds
    else Set.insert animId binds

-- | Get the current bind state for an animation ID.
getBindState :: AnimationState -> Int -> IO Bool
getBindState animState animId = do
  binds <- readIORef (asBindState animState)
  return $ Set.member animId binds

-- | Set multiple bind states at once.
-- Takes a map of animation ID -> enabled state.
setBindState :: AnimationState -> Map Int Bool -> IO ()
setBindState animState bindMap = do
  let enabledIds = Map.keys $ Map.filter id bindMap
  writeIORef (asBindState animState) (Set.fromList enabledIds)

-- | Get all enabled bind animation IDs.
getEnabledBinds :: AnimationState -> IO (Set Int)
getEnabledBinds animState = readIORef (asBindState animState)

-- | Check if an exclusive animation is currently running.
isExclusiveRunning :: AnimationState -> IO Bool
isExclusiveRunning animState = do
  mExcl <- readIORef (asExclusiveAnim animState)
  return $ case mExcl of
    Nothing -> False
    Just _  -> True

-- | Process queued animations when exclusive animation finishes.
-- Should be called after each tick to check if queued animations can start.
processQueue :: AnimationState -> SurfaceDefinition -> [ ActiveAnim ] -> IO [ ActiveAnim ]
processQueue animState surfDef activeAnims = do
  mExcl <- readIORef (asExclusiveAnim animState)
  case mExcl of
    Just _  -> return activeAnims  -- Still running exclusive
    Nothing -> do
      queue <- readIORef (asAnimQueue animState)
      if null queue
        then return activeAnims
        else do
          -- Start all queued animations
          newAnims <- catMaybes <$> mapM (`startAnimation` False) queue
          writeIORef (asAnimQueue animState) []
          return (activeAnims ++ newAnims)

-- | Check if animation has exclusive option
hasExclusiveOption :: Animation -> Bool
hasExclusiveOption anim = any isExclusive (animOptions anim)
  where
    isExclusive (OptionExclusive _) = True
    isExclusive _ = False

-- | Invoke all YenE animations for a surface.
-- Should be called when \e tag is encountered in script.
-- If exclusive animation is running, queues instead.
invokeYenE :: AnimationState -> SurfaceDefinition -> [ ActiveAnim ] -> IO [ ActiveAnim ]
invokeYenE animState surfDef activeAnims = do
  mExcl <- readIORef (asExclusiveAnim animState)
  let runningIds = map (animId . aaDef) activeAnims
      yenEAnims  = filter (isYenEInterval . animInterval) (sdAnimations surfDef)
      candidates = filter (\a -> animId a `notElem` runningIds) yenEAnims

  case mExcl of
    Just _  -> do
      -- Queue animations instead of starting
      modifyIORef' (asAnimQueue animState) (++ candidates)
      return activeAnims
    Nothing -> do
      newAnims <- catMaybes <$> mapM (`startAnimation` False) candidates
      -- Check if any started animation is exclusive
      mapM_ (checkAndSetExclusive animState) newAnims
      return (activeAnims ++ newAnims)
  where
    isYenEInterval :: AnimationInterval -> Bool
    isYenEInterval IntervalYenE = True
    isYenEInterval (IntervalCombined intervals) = any isYenEInterval intervals
    isYenEInterval _ = False

-- | Set exclusive state if animation has exclusive option
checkAndSetExclusive :: AnimationState -> ActiveAnim -> IO ()
checkAndSetExclusive animState anim
  = when (hasExclusiveOption (aaDef anim))
  $ writeIORef (asExclusiveAnim animState) (Just (animId (aaDef anim)))

-- | Invoke talk animations for a surface.
-- Should be called when character count threshold is reached.
-- The Int parameter is the current character count.
-- Only triggers animations where (charCount `mod` talkN) == 0.
-- If exclusive animation is running, queues instead.
invokeTalk :: AnimationState -> SurfaceDefinition -> [ ActiveAnim ] -> Int -> IO [ ActiveAnim ]
invokeTalk animState surfDef activeAnims charCount = do
  mExcl <- readIORef (asExclusiveAnim animState)
  let runningIds = map (animId . aaDef) activeAnims
      talkAnims  = filter (shouldTrigger . animInterval) (sdAnimations surfDef)
      candidates = filter (\a -> animId a `notElem` runningIds) talkAnims

  case mExcl of
    Just _  -> do
      -- Queue animations instead of starting
      modifyIORef' (asAnimQueue animState) (++ candidates)
      return activeAnims
    Nothing -> do
      newAnims <- catMaybes <$> mapM (`startAnimation` False) candidates
      -- Check if any started animation is exclusive
      mapM_ (checkAndSetExclusive animState) newAnims
      return (activeAnims ++ newAnims)
  where
    shouldTrigger :: AnimationInterval -> Bool
    shouldTrigger (IntervalTalk n) = n > 0 && charCount `mod` n == 0
    shouldTrigger (IntervalCombined intervals) = any shouldTrigger intervals
    shouldTrigger _ = False
